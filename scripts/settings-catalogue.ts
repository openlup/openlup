type SourceDescriptor = Omit<SettingDescriptor, "schema" | "previewSchema"> & {
  schema?: ZodType | SettingDescriptor["schema"];
  previewSchema?: ZodType | SettingDescriptor["previewSchema"];
};

export function parseSettingData(contents: string, domain: string): readonly SettingDescriptor[] {
  const raw: unknown = JSON.parse(contents);
  const entries = z.array(settingsToolOutputSchema.descriptor).parse(raw);
  if (entries.some(entry => entry.domain !== domain)) throw new Error(`Descriptor does not belong to ${domain}`);
  // The strict schema has no transforms. Keep the authored property order in the generated bytes.
  return raw as typeof entries;
}

function readSettingDescriptors(root: string): readonly SourceDescriptor[] {
  const source = join(root, "packages/platform/src");
  const domains = readdirSync(source, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort();
  const data = domains.flatMap(name => {
    const path = join(source, name, "settings-data.json");
    const file = lstatSync(path, { throwIfNoEntry: false });
    if (!file) return [];
    if (!file.isFile()) throw new Error(`Expected a regular settings data file at ${path}`);
    try {
      return parseSettingData(readFileSync(path, "utf8"), name);
    } catch (cause) {
      throw new Error(`Invalid settings data in ${path}`, { cause });
    }
  });
  return [describeRenewalStockProtectionSetting(), ...data];
}

function settingCommand(key: string, connected = false): string {
  const database = connected ? " --database-url <read-capable-url>" : "";
  return `node --experimental-strip-types host/settings.ts show ${key}${database} --json`;
}

function isZod(schema: ZodType | Record<string, unknown>): schema is ZodType {
  return typeof schema.safeParse === "function";
}

function describeSetting(entry: SourceDescriptor) {
  const { schema, previewSchema, rules, ...metadata } = entry;
  return {
    ...metadata,
    schema: schema ? (isZod(schema) ? toolInputSchema(schema) : schema) : null,
    previewSchema: previewSchema ? (isZod(previewSchema) ? toolInputSchema(previewSchema, "output") : previewSchema) : null,
    rules: rules.map(({ code, path, description }) => ({ code, path, description })),
  };
}

