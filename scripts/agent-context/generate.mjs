/** Preserve exact LF source bytes, including its heading and trailing blank lines. */
export function extractSection(source, heading, stopBefore) {
  const lines = source.split('\n');
  const headings = [];
  let fence;
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index];
    const marker = line.match(/^ {0,3}(`{3,}|~{3,})/u)?.[1];
    if (fence) {
      if (marker?.[0] === fence[0] && marker.length >= fence.length && /^ {0,3}(?:`+|~+)\s*$/u.test(line)) fence = undefined;
      continue;
    }
    if (marker) { fence = marker; continue; }
    const match = line.match(/^(#{1,6}) (.+)$/u);
    if (match) headings.push({ line: index, level: match[1].length, title: match[2] });
  }
  const matches = headings.filter((entry) => entry.title === heading);
  if (matches.length !== 1) throw new Error(`Expected one owner heading ${JSON.stringify(heading)}; found ${matches.length}`);
  const start = matches[0];
  let end = headings.find((entry) => entry.line > start.line && entry.level <= start.level)?.line ?? lines.length - (source.endsWith('\n') ? 1 : 0);
  if (stopBefore) {
    const boundaries = lines.flatMap((line, index) => index > start.line && index < end && line.startsWith(stopBefore) && lines[index - 1] === '' ? [index] : []);
    if (boundaries.length !== 1) throw new Error(`Expected one paragraph boundary ${JSON.stringify(stopBefore)}; found ${boundaries.length}`);
    end = boundaries[0];
  }
  const excerpt = lines.slice(start.line, end).join('\n') + (end < lines.length - 1 || source.endsWith('\n') ? '\n' : '');
  if (excerpt.includes('<!-- openlup-context ') || excerpt.includes('<!-- /openlup-context -->')) throw new Error('Owner text contains reserved corpus markers');
  return { excerpt, startLine: start.line + 1, endLine: end };
}

export function generateCorpus(root, packageName) {
  const entries = routes[packageName];
  if (!entries) throw new Error(`Unknown package ${packageName}`);
  let output = `# @openlup/${packageName} agent context\n\n` +
    'Development-preview guidance. Generated by `node scripts/agent-context/generate.mjs`; do not edit.\n' +
    'Small offline excerpts from canonical owners at generation time; not installation or compatibility proof.\n' +
    'Each source span is verbatim, with one-based inclusive line numbers and a SHA-256 of its UTF-8 bytes.\n' +
    'Package-local source paths are relative to this package; docs/platform paths are repository-relative.\n' +
    'Relative links inside excerpts are relative to their original source file. Consult installed declarations and README for the installed version.\n\n';
  const inventory = [];
  let sections = '';
  for (const [id, title, source, heading, stopBefore] of entries) {
    const { excerpt, startLine, endLine } = extractSection(readFileSync(resolve(root, source), 'utf8'), heading, stopBefore);
    const sha256 = createHash('sha256').update(excerpt).digest('hex');
    const localPrefix = `packages/${packageName}/`;
    const metadata = { id, source: source.startsWith(localPrefix) ? source.slice(localPrefix.length) : source, heading, startLine, endLine, sha256 };
    inventory.push(metadata);
    sections += `## ${id}: ${title}\n\n<!-- openlup-context ${JSON.stringify(metadata)} -->\n${excerpt}` +
      '<!-- /openlup-context -->\n\n';
  }
  output += `<!-- openlup-context-inventory ${JSON.stringify(inventory)} -->\n\n${sections}`;
  if (Buffer.byteLength(output) > 12_000) throw new Error(`${packageName} corpus exceeds its 12 KB excerpt budget; narrow the task routes`);
  return output.slice(0, -1); // Keep one final newline, without an empty EOF line.
}

export function run(root, check = false) {
  const stale = [];
  for (const packageName of Object.keys(routes)) {
    const path = `packages/${packageName}/AGENT_CONTEXT.md`;
    const generated = generateCorpus(root, packageName);
    if (check) {
      let actual;
      try { actual = readFileSync(resolve(root, path), 'utf8'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (actual !== generated) stale.push(path);
    } else writeFileSync(resolve(root, path), generated);
  }
  if (stale.length) throw new Error(`Stale agent context: ${stale.join(', ')}. Run node scripts/agent-context/generate.mjs`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Usage: node scripts/agent-context/generate.mjs [--check]');
  run(resolve(dirname(fileURLToPath(import.meta.url)), '../..'), args[0] === '--check');
}
